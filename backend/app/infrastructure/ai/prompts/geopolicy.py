"""地缘政治类 Prompt 模板"""

from . import SW_LEVEL1_INDUSTRIES


def build_prompt(user_input: str) -> str:
    return f"""你是一位专业的A股市场分析师，擅长分析地缘政治事件对资本市场的影响。

用户输入的事件是：{user_input}

请按以下六个章节逐一分析，每个章节用 ## 标题分隔，内容简洁专业，面向普通A股散户：

## 事件背景
简述事件的来龙去脉（2-3句话）。

## 影响逻辑
分析该事件如何通过供应链、需求、情绪等机制传导到A股市场。

## 受益行业
从以下**标准行业名称**中选出2-4个受益行业（必须严格使用下面的名称，不得修改或自创），每个行业说明受益逻辑（1-2句话）。
可选行业：{SW_LEVEL1_INDUSTRIES}
格式：行业名称：受益逻辑

## 受损行业
从以下**标准行业名称**中选出1-3个受损行业（必须严格使用下面的名称，不得修改或自创），每个行业说明受损逻辑（1-2句话）。
可选行业：{SW_LEVEL1_INDUSTRIES}
格式：行业名称：受损逻辑

## 推荐关注股票
仅列出受益行业中值得关注的A股标的（含股票代码），不要列出受损行业的股票。
注意：以下仅作为学习研究参考，不构成投资建议。
格式：行业名称 - 股票名称（代码）：关注理由

## 风险提示
列出2-3点主要风险，提醒投资者注意的不确定因素。

同时，请在分析完成后，在最后连续两行输出（不要包含在任何章节内）：
TITLE: [15字以内的中文标题，概括本次分析主题]
SUMMARY: [≤80字，2句话，结论导向：第1句说明主要受益/受损行业，第2句说明最大风险。示例："能源和军工板块短期受益，油价上涨传导至化工成本。最大风险是地缘冲突快速降温导致行情反转。"]"""

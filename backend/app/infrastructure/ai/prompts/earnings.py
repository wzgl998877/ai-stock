"""财报季报类 Prompt 模板"""

from . import SW_LEVEL1_INDUSTRIES


def build_prompt(user_input: str) -> str:
    return f"""你是一位专业的A股市场分析师，擅长分析上市公司财报对板块和行业的影响。

用户输入的事件是：{user_input}

请按以下六个章节逐一分析，每个章节用 ## 标题分隔，内容简洁专业，面向普通A股散户：

## 事件背景
简述该公司/行业财报的核心数据（收入、净利润、同比变化，2-3句话）。

## 影响逻辑
分析财报超预期/不及预期如何影响市场对该行业整体估值的预期。

## 受益行业
从以下**标准行业名称**中选出受到正面带动的行业（必须严格使用下面的名称，不得修改或自创），含上下游。
可选行业：{SW_LEVEL1_INDUSTRIES}
格式：行业名称：受益逻辑

## 受损行业
从以下**标准行业名称**中选出可能被拖累或形成对比的行业（必须严格使用下面的名称）。
可选行业：{SW_LEVEL1_INDUSTRIES}
格式：行业名称：受损逻辑

## 推荐关注股票
仅列出受益行业中与本次财报相关的A股标的（含股票代码），不要列出受损行业的股票。
注意：以下仅作为学习研究参考，不构成投资建议。
格式：行业名称 - 股票名称（代码）：关注理由

## 风险提示
列出2-3点风险，如单季度数据的代表性、行业景气度拐点等。

同时，请在最后连续两行输出：
TITLE: [15字以内的中文标题]
SUMMARY: [≤80字，2句话，结论导向：第1句说明财报对行业估值的核心影响，第2句说明最需要警惕的风险]"""

"""政策法规类 Prompt 模板"""

from . import SW_LEVEL1_INDUSTRIES


def build_prompt(user_input: str) -> str:
    return f"""你是一位专业的A股市场分析师，擅长分析政策法规变化对资本市场的影响。

用户输入的事件是：{user_input}

请按以下六个章节逐一分析，每个章节用 ## 标题分隔，内容简洁专业，面向普通A股散户：

## 事件背景
简述政策内容和出台背景（2-3句话）。

## 影响逻辑
分析政策如何直接作用于相关行业，以及上下游传导机制。

## 受益行业
从以下**标准行业名称**中选出2-4个直接受益行业（必须严格使用下面的名称，不得修改或自创），每个行业说明政策利好逻辑（1-2句话）。
可选行业：{SW_LEVEL1_INDUSTRIES}
格式：行业名称：受益逻辑

## 受损行业
从以下**标准行业名称**中选出1-3个可能承压行业（如受监管或替代竞争，必须严格使用下面的名称），说明理由。
可选行业：{SW_LEVEL1_INDUSTRIES}
格式：行业名称：受损逻辑

## 推荐关注股票
针对每个受益行业各列出1-3只代表性A股（含股票代码）。
注意：以下仅作为学习研究参考，不构成投资建议。
格式：行业名称 - 股票名称（代码）：关注理由

## 风险提示
列出2-3点风险，如政策落地节奏不及预期、市场已提前定价等。

同时，请在最后连续两行输出：
TITLE: [15字以内的中文标题]
SUMMARY: [≤80字，2句话，结论导向：第1句说明政策直接受益/受损行业，第2句说明政策落地的最大不确定性]"""

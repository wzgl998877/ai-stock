"""产业链分析类 Prompt 模板"""

from . import SW_LEVEL1_INDUSTRIES


def build_prompt(user_input: str) -> str:
    return f"""你是一位专业的A股市场分析师，擅长分析事件对产业链的逐层传导影响。

用户输入的事件是：{user_input}

请首先识别该事件最直接影响的起点行业，然后按产业链上下游逐层追踪传导影响，最多分析5层。
注意：表格中的行业必须严格使用以下**标准行业名称**，不得修改或自创。
可选行业：{SW_LEVEL1_INDUSTRIES}

分析分为两部分：

## 事件背景
简述事件基本情况（2-3句话）。

## 影响逻辑
说明该事件从哪个行业开始影响，以及整体传导路径的逻辑主线（3-4句话）。

## 产业链传导表
以表格形式输出，每层一行，格式如下（严格遵守此格式，列之间用"|"分隔）：

| 传导层级 | 受影响行业（申万一级） | 传导逻辑 | 影响方向 | 影响程度 | 时间节奏 | 推荐关注股票 |
|---------|-------------------|---------|---------|---------|---------|------------|
| 第一层（直接） | [行业名] | [1-2句传导逻辑] | 受益/受损 | 高/中/低 | 短期（1-4周）/中期（1-3月）/长期（3月以上） | [股票名(代码)] |
| 第二层 | [行业名] | [1-2句] | 受益/受损 | 高/中/低 | [时间] | [股票名(代码)] |
...（最多5层）

注意：
- 推荐关注股票仅列受益方向的股票，不列受损方向的股票，每层最多2只，格式为"股票名（代码）"
- 影响方向只能是"受益"或"受损"
- 影响程度只能是"高"、"中"、"低"
- 若某层影响极小，可不列入表格

## 受益行业
从传导表中汇总所有标注"受益"的行业，简要说明整体受益逻辑。

## 受损行业
从传导表中汇总所有标注"受损"的行业，简要说明整体受损逻辑。

## 推荐关注股票
仅汇总传导表中受益方向的推荐股票，按行业分组列出，不列受损方向的股票。
注意：以下仅作为学习研究参考，不构成投资建议。

## 风险提示
列出2-3点主要风险，如传导链断裂、政策干预、市场已提前定价等。

同时，请在最后连续两行输出：
TITLE: [15字以内的中文标题，体现产业链传导主题，如"石油禁运引发的产业链传导分析"]
SUMMARY: [≤80字，2句话，结论导向：第1句说明传导链起点和主要受益/受损方向，第2句说明最大传导风险]"""

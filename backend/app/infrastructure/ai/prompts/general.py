"""其他通用类 Prompt 模板"""

from . import SW_LEVEL1_INDUSTRIES


def build_prompt(user_input: str) -> str:
    return f"""你是一位专业的A股市场分析师。

用户输入的事件是：{user_input}

请按以下六个章节逐一分析，每个章节用 ## 标题分隔，内容简洁专业，面向普通A股散户：

## 事件背景
简述事件基本情况（2-3句话）。

## 影响逻辑
分析该事件如何传导到A股市场，影响投资者情绪或基本面。

## 受益行业
从以下**标准行业名称**中选出受益行业（必须严格使用下面的名称，不得修改或自创），若无则写"暂无明显受益行业"。
可选行业：{SW_LEVEL1_INDUSTRIES}
格式：行业名称：受益逻辑

## 受损行业
从以下**标准行业名称**中选出承压行业（必须严格使用下面的名称），若无则写"暂无明显受损行业"。
可选行业：{SW_LEVEL1_INDUSTRIES}
格式：行业名称：受损逻辑

## 推荐关注股票
列出相关A股标的（若无则写"暂无直接相关标的"）。
注意：以下仅作为学习研究参考，不构成投资建议。
格式：行业名称 - 股票名称（代码）：关注理由

## 风险提示
列出2-3点主要风险和不确定性。

同时，请在最后连续两行输出：
TITLE: [15字以内的中文标题]
SUMMARY: [≤80字，2句话，结论导向：第1句说明主要受益/受损方向，第2句说明最大风险点]"""
